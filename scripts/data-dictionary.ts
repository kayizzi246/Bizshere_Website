/**
 * Generates docs/03-database/data-dictionary.md from prisma/schema.prisma.
 *
 *   npm run docs:db
 *
 * Run it after every schema change so the dictionary never drifts from the database.
 * Table descriptions come from the `///` comments in schema.prisma.
 */
import { Prisma } from "@prisma/client";
import { writeFileSync, mkdirSync } from "node:fs";
import path from "node:path";

/** Tables grouped by blueprint section. Every model must appear exactly once. */
const GROUPS: [string, string[]][] = [
  ["03 Shared publishing layer", ["ContentItem", "ContentCategory", "ContentLocation", "ContentAudience", "ContentEntitlement", "Category", "Audience", "Location", "Unit", "Source", "EvidenceLink", "MediaAsset", "FileVersion", "VerificationCheck", "RelatedContent", "ContentRevision"]],
  ["People and organizations", ["User", "Organization", "OrganizationMember", "OrganizationCategory", "OrganizationLocation", "Contact"]],
  ["04 Business ideas and plans", ["BusinessIdea", "IdeaStep", "BudgetScenario", "BudgetLine"]],
  ["05 Business machines", ["Machine", "SupplierOffer"]],
  ["06 Suppliers", ["Supplier", "SupplierProductListing"]],
  ["07 Funding sources", ["FundingProvider", "FundingProgramme", "ApplicationRound"]],
  ["08 Guidelines and investment opportunities", ["Guide", "GuideStep", "GuideDocument", "GuideFee", "InvestmentOpportunity"]],
  ["09 Consultants and experts", ["Consultant", "ConsultantQualification", "ConsultantService", "ConsultantProject", "ConsultantReview"]],
  ["10 Cooking recipes", ["Recipe", "RecipeIngredient", "RecipeStep", "RecipeCosting", "RecipeCostingLine"]],
  ["11 Tools and templates", ["Tool", "ToolVersion", "ToolTestCase", "ToolCalculation"]],
  ["12 Markets and prices", ["Market", "Product", "PriceObservation"]],
  ["13 Useful websites and business news", ["UsefulWebsite", "NewsArticle", "NewsOrganization"]],
  ["14/17 Membership, payments and saved items", ["MembershipPlan", "Subscription", "Payment", "SavedItem", "Collection", "CollectionItem", "SavedSearch", "Alert"]],
  ["14/18 Review, moderation and analytics", ["Submission", "ModerationEvent", "CorrectionReport", "Document", "Enquiry", "ContactReveal", "AuditLog", "SearchEvent", "UsageEvent"]],
  ["Site", ["SiteUpdate"]],
  ["Sign-in", ["PhoneCode"]],
];

const { models, enums } = Prisma.dmmf.datamodel;
const byName = new Map(models.map((m) => [m.name, m]));
const grouped = new Set(GROUPS.flatMap(([, names]) => names));
const ungrouped = models.filter((m) => !grouped.has(m.name)).map((m) => m.name);
if (ungrouped.length) throw new Error(`Add these models to a group in scripts/data-dictionary.ts: ${ungrouped.join(", ")}`);
const missing = [...grouped].filter((n) => !byName.has(n));
if (missing.length) throw new Error(`Grouped models not in schema: ${missing.join(", ")}`);

const table = (name: string) => byName.get(name)?.dbName ?? name;
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");

const out: string[] = [];
out.push("# Data dictionary");
out.push("");
out.push("> Generated by `npm run docs:db` from `prisma/schema.prisma`. Do not edit by hand.");
out.push("");
out.push(`${models.length} tables, ${enums.length} enumerations. Column names are as Prisma writes them (camelCase, quoted in SQL, e.g. \`"priceMin"\`).`);
out.push("Extra CHECK rules and indexes that Prisma can't express live in `prisma/sql/constraints.sql`.");
out.push("");
out.push("**Key:** PK primary key · FK foreign key · ? optional (NULL allowed) · [] list (PostgreSQL array) · UQ unique");
out.push("");
out.push("## Contents");
out.push("");
for (const [g, names] of GROUPS) {
  out.push(`- **${g}:** ${names.map((n) => `[${table(n)}](#${table(n).replace(/_/g, "_")})`).join(", ")}`);
}
out.push("- [Enumerations](#enumerations)");
out.push("");

for (const [g, names] of GROUPS) {
  out.push(`## ${g}`);
  out.push("");
  for (const n of names) {
    const m = byName.get(n)!;
    out.push(`### ${table(n)}`);
    out.push("");
    out.push(`Prisma model \`${m.name}\`.${m.documentation ? ` ${esc(m.documentation)}` : ""}`);
    out.push("");
    out.push("| Column | Type | Notes |");
    out.push("|---|---|---|");
    const pk = new Set(m.primaryKey?.fields ?? []);
    const uniques = new Set(m.uniqueFields.filter((u) => u.length === 1).flat());
    for (const f of m.fields) {
      if (f.kind === "object") continue; // relation fields are shown via their FK column
      const rel = m.fields.find((r) => r.kind === "object" && r.relationFromFields?.includes(f.name));
      const notes: string[] = [];
      if (f.isId || pk.has(f.name)) notes.push("PK");
      if (f.isUnique || uniques.has(f.name)) notes.push("UQ");
      if (rel) notes.push(`FK → ${table(rel.type)}${rel.relationOnDelete ? ` (on delete ${rel.relationOnDelete.toLowerCase()})` : ""}`);
      if (f.hasDefaultValue) {
        const d = f.default as unknown;
        const shown = typeof d === "object" && d !== null && "name" in d ? `${(d as { name: string }).name}()` : JSON.stringify(d);
        notes.push(`default ${shown}`);
      }
      if (f.isUpdatedAt) notes.push("auto-updated");
      if (f.documentation) notes.push(esc(f.documentation));
      const type = `${f.kind === "enum" ? `[${f.type}](#${f.type.toLowerCase()})` : f.type}${f.isList ? "[]" : ""}${f.isRequired || f.isList ? "" : "?"}`;
      out.push(`| \`${f.name}\` | ${type} | ${notes.join(" · ")} |`);
    }
    const children = m.fields.filter((f) => f.kind === "object" && f.isList).map((f) => table(f.type));
    if (m.primaryKey && m.primaryKey.fields.length > 1) out.push(`\nComposite primary key: (${m.primaryKey.fields.join(", ")}).`);
    const multiUq = m.uniqueFields.filter((u) => u.length > 1);
    if (multiUq.length) out.push(`\nUnique together: ${multiUq.map((u) => `(${u.join(", ")})`).join("; ")}.`);
    if (children.length) out.push(`\nReferenced by: ${[...new Set(children)].join(", ")}.`);
    out.push("");
  }
}

out.push("## Enumerations");
out.push("");
for (const e of enums) {
  out.push(`### ${e.name}`);
  out.push("");
  out.push(e.values.map((v) => `\`${v.name}\``).join(" · "));
  out.push("");
}

const file = path.join("docs", "03-database", "data-dictionary.md");
mkdirSync(path.dirname(file), { recursive: true });
writeFileSync(file, out.join("\n"));
console.log(`Wrote ${file} (${models.length} tables, ${enums.length} enums)`);
