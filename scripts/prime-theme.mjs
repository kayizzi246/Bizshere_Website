// Builds src/styles/primereact-theme.css: PrimeReact's Lara Light Amber theme recoloured
// to the BizSphere blue (tailwind.config.ts) and wrapped in the `primereact` CSS layer,
// so Tailwind utilities always override it. Re-run after upgrading primereact:
//   npm run theme:prime
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = require.resolve("primereact/resources/themes/lara-light-amber/theme.css");
const target = join(root, "src/styles/primereact-theme.css");

// Amber -> brand blue. Keys are lowercase hex as they appear in the Lara theme.
const colours = {
  "#f59e0b": "#0072CE", // primary (brand.DEFAULT)
  "#d97706": "#0166B9", // primary hover
  "#b45309": "#005BA6", // primary active / highlight text (brand.dark)
  "#fffbeb": "#E8F2FB", // highlight background (brand.tint)
  "#fde68a": "#CFE5F7", // brand.sky
  "#fef08a": "#A9D1F2", // focus ring
};
const scale = {
  50: "#E8F2FB", 100: "#CFE5F7", 200: "#A9D1F2", 300: "#6DB1EA", 400: "#2E8BDC",
  500: "#0072CE", 600: "#0166B9", 700: "#005BA6", 800: "#01467F", 900: "#012F55",
};

let css = readFileSync(source, "utf8");

// Fonts: Inter is already self-hosted by next/font (src/app/layout.tsx).
css = css.replace(/@font-face\s*{[^}]*}\s*/g, "");
css = css.replaceAll('"Inter var", sans-serif', "var(--font-inter), system-ui, sans-serif");

for (const [from, to] of Object.entries(colours)) css = css.replace(new RegExp(from, "gi"), to);
css = css.replace(/rgba\(245, 158, 11,/g, "rgba(0, 114, 206,");
css = css.replace(/--primary-(\d+):#[0-9a-f]{6};/gi, (_, step) => `--primary-${step}:${scale[step]};`);

mkdirSync(dirname(target), { recursive: true });
writeFileSync(
  target,
  `/* Generated by scripts/prime-theme.mjs from primereact lara-light-amber. Do not edit. */\n` +
    // This file loads before globals.css, and the first layer statement fixes the order,
    // so it repeats the order declared there.
    `@layer tailwind-base, primereact, tailwind-utilities;\n` +
    `@layer primereact {\n${css}\n}\n`,
);
console.log(`Wrote ${target}`);
